const atk = (pattern: string, interval: number, delay = 0.8, extra: Partial<AttackDef> = {}): AttackDef => ({ pattern, interval, delay, ...extra });

/** Extended def info used by describeEnemy / ENEMY_NOTES (not part of the contract). */
export interface EnemyMeta {
  chapters: string;
  notes: string;
}

export const ENEMY_META: Record<string, EnemyMeta> = {};

function def(d: EnemyDef, meta: EnemyMeta): EnemyDef {
  ENEMY_META[d.id] = meta;
  return d;
}

